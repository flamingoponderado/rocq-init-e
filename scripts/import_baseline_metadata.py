#!/usr/bin/env python3
"""Import only baseline FFI/MMIO literals from the pinned software guest config.

This does not certify compiler output or ROM bytes. The native anchor and ROM
length are independent layout literals whose binding is a separate obligation.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATH = Path('source/init-e-baseline/CompilerConfigLiteral.lean')
SOURCE_SHA256 = 'f20ae8ed9d9f5767e6e0e610dba99a89cbcbac218e857a516d0880bff3fbb465'
TARGET = ROOT / 'theories/Baseline/Metadata.v'


def bracket_list(text, marker):
    start = text.index('[', text.index(marker))
    depth = 0
    quoted = False
    for end in range(start, len(text)):
        char = text[end]
        if char == '"':
            quoted = not quoted
        if not quoted:
            depth += (char == '[') - (char == ']')
            if depth == 0:
                return text[start + 1:end]
    raise ValueError('unclosed list: ' + marker)


def parse(source):
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError('software guest config differs from pinned source SHA256')
    text = source.decode('utf-8')
    body = bracket_list(text, 'ffiNames := some [')
    name_pattern = re.compile(
        r'\.extCall \(Flapjack\.Basis\.Pure\.MlString\.ofString "([a-z0-9_]+)"\)'
        r'|\.sharedMem \.(mappedRead|mappedWrite)')
    names = []
    for item in body.split(','):
        match = name_pattern.fullmatch(item.strip())
        if match is None:
            raise ValueError('unsupported FFI literal: ' + item)
        names.append(('ExtCall', match[1]) if match[1] else ('SharedMem', match[2]))
    body = bracket_list(text, 'shmemExtra := [')
    record_pattern = re.compile(
        r'\{ entryPc := ([0-9]+), nbytes := BitVec\.ofNat 8 ([0-9]+), '
        r'addrReg := ([0-9]+), addrOff := ([0-9]+), reg := ([0-9]+), exitPc := ([0-9]+) \}')
    records = []
    cursor = 0
    for match in record_pattern.finditer(body):
        if body[cursor:match.start()].strip() != (',' if cursor else ''):
            raise ValueError('unsupported MMIO syntax')
        records.append(tuple(int(x) for x in match.groups()))
        cursor = match.end()
    if body[cursor:].strip():
        raise ValueError('trailing MMIO syntax')
    if len(names) != 17 or len(records) != 15:
        raise ValueError('unexpected software guest metadata lengths')
    if names[:2] != [('ExtCall', 'trap'), ('ExtCall', 'halt')] or \
       any(kind != 'SharedMem' for kind, _ in names[2:]):
        raise ValueError('software guest metadata contains accelerator FFI')
    if any(record[1] >= 256 for record in records):
        raise ValueError('MMIO byte literal overflow')
    return names, records


def render(source):
    names, records = parse(source)
    out = [
        '(** Literal metadata from pinned software guest CompilerConfigLiteral.lean.',
        '    SHA256: ' + SOURCE_SHA256,
        '    Generated by scripts/import_baseline_metadata.py; do not edit.',
        '    This is not a compiler equality or a ROM installation theorem. *)',
        'From Galette Require Import Base.',
        'From Galette.HOL.src.n_bit Require Import words.',
        'From Galette.HOL.src.list.src Require Import list rich_list.',
        'From Galette.HOL.src.string Require Import string.',
        'From Galette.cakeml.basis.pure Require Import mlstring.',
        'From Galette.cakeml.semantics.ffi Require Import ffi.',
        'From Galette.cakeml.compiler.backend Require lab_to_target.',
        'Open Scope N_scope.',
        '(** Software guest BootstrapMemory.lean nativePc and ROM length.',
        '    Their binding to a concrete submitted ROM remains separate. *)',
        'Definition baselineNativePc : N := 2147487856.',
        'Definition baselineRomLength : N := 1028080.',
        'Definition baselineFirst : N := 2.',
        'Definition baselineNames : list ffiname := [']
    out.append(';\n'.join(' ExtCall (strlit "' + value + '")' if kind == 'ExtCall' else
                         ' SharedMem ' + ('MappedRead' if value == 'mappedRead' else 'MappedWrite')
                         for kind, value in names) + '].')
    out.append('Definition baselineMmio : list lab_to_target.shmem_info_num := [')
    fields = ['entry_pc', 'nbytes', 'addr_reg', 'addr_off', 'reg', 'exit_pc']
    out.append(';\n'.join(' {| ' + '; '.join('lab_to_target.' + field + ' := ' +
                          ('n2w ' if field == 'nbytes' else '') + str(value)
                          for field, value in zip(fields, record)) + ' |}'
                          for record in records) + '].')
    out.extend([
        'Definition baselineDispatchAddress (i : N) : word 64 :=',
        ' (n2w baselineNativePc - n2w ((1+i)*lab_to_target.ffi_offset))%w.',
        'Definition baselineEntryPcs : list (word 64) :=',
        ' MAP (fun i => (n2w baselineNativePc - n2w ((3+i)*lab_to_target.ffi_offset))%w)',
        '  (COUNT_LIST baselineFirst) ++',
        ' MAP (fun rec => (n2w baselineNativePc + n2w (lab_to_target.entry_pc rec))%w) baselineMmio.',
        ''])
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--references-root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = render((args.references_root / SOURCE_PATH).read_bytes())
    if args.check:
        if TARGET.read_text() != generated:
            raise SystemExit('baseline metadata differs from pinned original')
    else:
        TARGET.write_text(generated)


if __name__ == '__main__':
    main()
