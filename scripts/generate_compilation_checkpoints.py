#!/usr/bin/env python3
"""Generate per-function, per-pass kernel computation checkpoints.

Generated sources are checked in under theories/Compilation.
Run after Frontend.vo has been built. The function count is obtained from
Frontend.words (not guessed from source declarations, since lowering adds stubs).
Generated .v files are ordinary proofs; this script is outside the trust base.
"""
import argparse
from pathlib import Path
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parents[1]
HEADER = '''(** Generated by scripts/generate_compilation_checkpoints.py. *)
From Galette Require Import Base.
From Galette.cakeml.translator.monadic.monad_base Require Import ml_monadBase.
From Galette.HOL.src.list.src Require Import list.
From Galette.cakeml.compiler.backend Require wordLang word_to_word word_simp
 word_inst word_alloc word_cse word_copy word_unreach word_remove.
From Galette.cakeml.compiler.encoders.asm Require asm.
From Galette.cakeml.compiler.encoders.riscv Require riscv_target.
From InitE.Compilation Require Import Frontend.
Open Scope N_scope.
From InitE.Compilation Require Import CompilerConfig.
From InitE.Compilation Require FastGraph FastAllocation.
'''


def checkpoint(name, expression, fast_expression=None, exact=None):
    compute = fast_expression or expression
    proof = f'rewrite <- {exact}. ' if exact else ''
    return (f'Definition {name} := Eval vm_compute in {compute}.\n'
            f'Lemma {name}_eq : {expression} = {name}.\n'
            f'Proof. {proof}vm_cast_no_check (eq_refl {name}). Qed.\n')


def function(index):
    text = HEADER + f'''Definition input := Eval vm_compute in
 List.nth {index} Frontend.words (0,(0,wordLang.Skip)).
Definition name := Eval vm_compute in fst input.
Definition argc := Eval vm_compute in fst (snd input).
Definition body := Eval vm_compute in snd (snd input).
'''
    stages = [
        ('simp', 'word_simp.compile_exp body'),
        ('inst', 'word_inst.inst_select ac (wordLang.max_var simp + 1) simp'),
        ('ssa', 'word_alloc.full_ssa_cc_trans argc inst'),
        ('dead1', 'word_alloc.remove_dead_prog ssa'),
        ('cse', 'word_cse.word_common_subexp_elim dead1'),
        ('copy', 'word_copy.copy_prop cse'),
        ('two', 'word_inst.three_to_two_reg_prog (asm.two_reg_arith ac) copy'),
        ('unreach', 'word_unreach.remove_unreach two'),
        ('dead2', 'word_alloc.remove_dead_prog unreach'),
        ('final', 'word_remove.remove_must_terminate alloc'),
    ]
    for name, expr in stages:
        if name == 'final':
            for n, e in [
                ('clashes', 'word_alloc.get_clash_tree dead2 []'),
                ('stack_only', 'word_alloc.get_stack_only dead2'),
                ('forced', 'word_alloc.get_forced ac dead2 []'),
                ('heuristics', 'word_alloc.get_heuristics alg name dead2'),
                ('colouring', 'word_alloc.select_reg_alloc alg (snd heuristics) regs (fst heuristics) clashes forced stack_only'),
                ('alloc', 'match colouring with M_success col => word_alloc.apply_colour (word_alloc.total_colour col) dead2 | M_failure _ => dead2 end'),
            ]:
                if n == 'colouring':
                    text += checkpoint(n, e, e.replace('word_alloc.select_reg_alloc', 'FastAllocation.select_reg_alloc_fast'),
                                       'FastAllocation.select_reg_alloc_fast_exact')
                else:
                    text += checkpoint(n, e)
            text = text.replace('Lemma alloc_eq :', 'Lemma alloc_result_eq :')
            text += '''Lemma alloc_eq : word_alloc.word_alloc name ac alg regs dead2 None = alloc.
Proof.
 unfold word_alloc.word_alloc.
 cbv beta iota zeta delta [word_alloc.oracle_colour_ok].
 rewrite clashes_eq, stack_only_eq, forced_eq, heuristics_eq.
 change ((match word_alloc.select_reg_alloc alg (snd heuristics) regs
 (fst heuristics) clashes forced stack_only with
 | M_success col => word_alloc.apply_colour (word_alloc.total_colour col) dead2
 | M_failure _ => dead2 end) = alloc).
 rewrite colouring_eq, alloc_result_eq. reflexivity.
Qed.
'''
        text += checkpoint(name, expr)
    text += '''Definition output := (name,(argc,final)).
Theorem compiled_eq : word_to_word.full_compile_single
 (asm.two_reg_arith ac) regs alg ac (input,None) = output.
Proof.
 change (word_to_word.full_compile_single (asm.two_reg_arith ac) regs alg ac
 ((name,(argc,body)),None) = output).
 unfold word_to_word.full_compile_single, word_to_word.compile_single.
 cbv beta iota zeta.
'''
    text += ' rewrite ' + ', '.join(n+'_eq' for n,_ in stages[:-1]) + ', alloc_eq, final_eq' + '.\n reflexivity.\nQed.\n'
    return text


def aggregate(count):
    modules = [f'Word{i:04}' for i in range(count)]
    text = HEADER + 'From InitE.InitE Require Import BaselineCompiler.\n' + 'From InitE.Compilation Require ' + ' '.join(modules) + '.\n'
    inputs = '[' + ';'.join(m+'.input' for m in modules) + ']'
    outputs = '[' + ';'.join(m+'.output' for m in modules) + ']'
    pairs = '[' + ';'.join('('+m+'.input,None)' for m in modules) + ']'
    text += f'Definition optimized := {outputs}.\n'
    text += f'Lemma inputs_eq : Frontend.words = {inputs}.\n'
    text += 'Proof. vm_cast_no_check (eq_refl Frontend.words). Qed.\n'
    text += """Theorem word_pipeline_eq : word_to_word.compile
 (backend.word_to_word_conf baselineBackendConfig) ac Frontend.words = ([],optimized).
Proof.
 unfold word_to_word.compile.
 rewrite inputs_eq.
"""
    text += f' change ((([] : list (option (sptree.num_map N))), List.map (word_to_word.full_compile_single (asm.two_reg_arith ac) regs alg ac) {pairs}) = ([],optimized)).\n'
    text += ' unfold optimized.\n cbv beta iota fix delta [List.map].\n'
    for module in modules:
        text += f' rewrite {module}.compiled_eq.\n'
    text += ' reflexivity.\nQed.\n'
    return text


def split_allocation(i, root):
    prefix=f'Word{i:04}'
    base=function(i)
    a=base.index('Definition colouring :=')
    b=base.index('Definition alloc :=',a)
    extra='''From Galette.cakeml.compiler.backend.reg_alloc Require reg_alloc.
    From InitE.Compilation Require Import Allocation.
    '''
    modules=[]
    def emit(suffix,content):
        name=prefix+'_'+suffix
        text=HEADER+extra
        if modules:text+='From InitE.Compilation Require Import '+' '.join(modules)+'.\n'
        text+=content
        write_if_changed(root/(name+'.v'), text)
        modules.append(name)
    emit('00Input',base[len(HEADER):a]+checkpoint('bijection','reg_alloc.mk_bij clashes')+checkpoint('moves0','list.MAP (reg_alloc.update_move (reg_alloc.sp_default (fst bijection))) (fst heuristics)')+checkpoint('prefs','reg_alloc.resort_moves (reg_alloc.moves_to_sp moves0 sptree.LN)'))
    emit('01aGraph',checkpoint('graph','reg_alloc.mk_graph (reg_alloc.sp_default (fst bijection)) clashes [] (initialState (snd (snd bijection)))', 'FastGraph.mk_graph_fast (reg_alloc.sp_default (fst bijection)) clashes [] (initialState (snd (snd bijection)))', 'FastGraph.mk_graph_fast_exact'))
    emit('01bForced',checkpoint('extended','advance graph (fun _ => FastGraph.extend_graph_fast (reg_alloc.sp_default (fst bijection)) forced)')+'''Lemma extended_original_eq : advance graph (fun _ => reg_alloc.extend_graph (reg_alloc.sp_default (fst bijection)) forced) = extended.
    Proof.
     rewrite <- FastAllocation.advance_extend_graph_exact. exact extended_eq.
    Qed.
    ''')
    emit('01cInit',checkpoint('initialized','advance extended (fun _ => reg_alloc.mk_tags (snd (snd bijection)) stack_only (reg_alloc.sp_default (fst (snd bijection))))').replace('Lemma initialized_eq :','Lemma initialized_result_eq :')+'''Lemma initialized_eq : reg_alloc.init_ra_state clashes forced stack_only bijection (initialState (snd (snd bijection))) = initialized.
    Proof.
     change (reg_alloc.init_ra_state clashes forced stack_only
     (fst bijection,(fst (snd bijection),snd (snd bijection))) (initialState (snd (snd bijection))) = initialized).
     rewrite initialization_phases.
     rewrite graph_eq, extended_original_eq, initialized_result_eq. reflexivity.
    Qed.
    ''')
    emit('02Filter',checkpoint('filtered','advance initialized (fun _ => reg_alloc.st_ex_FILTER (fun \'(_, (x,y)) => reg_alloc.full_consistency_ok regs x y) moves0 [])'))
    emit('03aHeuristics', 'From InitE.Compilation Require SparseIRC.\n' + checkpoint('selectionInitialized','advance filtered (fun moves s => reg_alloc.init_alloc1_heu moves (reg_alloc.dim s) regs s)', 'advance filtered (fun moves => SparseIRC.initialize_fast moves regs)', 'SparseIRC.advance_initialize_fast_exact'))
    emit('03bLoop','From InitE.Compilation Require SparseIRC.\n'+checkpoint('selectionLoop','advance selectionInitialized (fun count => reg_alloc.rpt_do_step (snd heuristics) regs count)', 'advance selectionInitialized (fun count => SparseIRC.repeat_fast (snd heuristics) regs count)', 'SparseIRC.advance_repeat_fast_exact'))
    emit('03cSelect','From InitE.Compilation Require IRCSelection.\n'+checkpoint('selected','advance selectionLoop (fun _ => reg_alloc.get_stack)').replace('Lemma selected_eq :','Lemma selected_result_eq :')+'''Lemma selected_eq : advance filtered (fun moves => reg_alloc.do_alloc1 moves (snd heuristics) regs) = selected.
    Proof.
     rewrite IRCSelection.selection_phases.
     unfold IRCSelection.initialize_selection.
     rewrite selectionInitialized_eq, selectionLoop_eq, selected_result_eq. reflexivity.
    Qed.
    ''')
    emit('04AssignA',checkpoint('assignedA','advance selected (fun ls => reg_alloc.assign_Atemps regs ls (reg_alloc.biased_pref prefs))'))
    emit('05AssignS',checkpoint('assignedS','advance assignedA (fun _ => reg_alloc.assign_Stemps regs (reg_alloc.neg_biased_pref regs prefs))'))
    emit('06Colour',checkpoint('extracted','advance assignedS (fun _ => reg_alloc.extract_color (fst bijection))')+checkpoint('colouring','fst extracted')+'''Lemma colouring_pipeline_eq : word_alloc.select_reg_alloc alg (snd heuristics) regs (fst heuristics) clashes forced stack_only = colouring.
    Proof.
     change (reg_alloc.reg_alloc reg_alloc.IRC (snd heuristics) regs (fst heuristics) clashes forced stack_only = colouring).
     unfold reg_alloc.reg_alloc. rewrite bijection_eq.
     change (reg_alloc.reg_alloc_aux reg_alloc.IRC (snd heuristics) regs (fst heuristics) clashes forced stack_only
     (fst bijection,(fst (snd bijection),snd (snd bijection))) = colouring).
     rewrite allocator_phases. cbv beta iota zeta.
     fold bijection.
     rewrite moves0_eq, prefs_eq.
     change (fst (advance (advance (advance (advance (advance (reg_alloc.init_ra_state clashes forced stack_only bijection (initialState (snd (snd bijection)))) (fun _ => reg_alloc.st_ex_FILTER (fun '(_, (x,y)) => reg_alloc.full_consistency_ok regs x y) moves0 [])) (fun moves => reg_alloc.do_alloc1 moves (snd heuristics) regs)) (fun ls => reg_alloc.assign_Atemps regs ls (reg_alloc.biased_pref prefs))) (fun _ => reg_alloc.assign_Stemps regs (reg_alloc.neg_biased_pref regs prefs))) (fun _ => reg_alloc.extract_color (fst bijection))) = colouring).
     rewrite initialized_eq, filtered_eq, selected_eq, assignedA_eq, assignedS_eq, extracted_eq, colouring_eq.
     reflexivity.
    Qed.
    ''')
    text=HEADER+extra+'From InitE.Compilation Require Import '+' '.join(modules)+'.\n'
    text+=f'Definition input := {prefix}_00Input.input.\n'
    text+=base[b:]
    text=text.replace('rewrite colouring_eq, alloc_result_eq.','rewrite colouring_pipeline_eq, alloc_result_eq.')
    write_if_changed(root/(prefix+'.v'), text)

def split_word_passes(i, root):
    prefix = f'Word{i:04}'
    # Both the ordinary and split allocator templates have an input prefix.
    path = root / (prefix + '_00Input.v')
    split_allocator = path.exists()
    if not split_allocator:
        path = root / (prefix + '.v')
    text = path.read_text()
    start = text.index('Definition input :=')
    boundaries = ['Definition ssa :=', 'Definition cse :=', 'Definition clashes :=']
    offsets = [start] + [text.index(marker) for marker in boundaries]
    modules = []
    for j, suffix in enumerate(['Input', 'SSA', 'Optimize']):
        module = prefix + '_Pass' + suffix
        content = HEADER
        if modules:
            content += 'From InitE.Compilation Require Import ' + ' '.join(modules) + '.\n'
        content += text[offsets[j]:offsets[j+1]]
        write_if_changed(root / (module + '.v'), content)
        modules.append(module)
    content = text[:start] + 'From InitE.Compilation Require Export ' + ' '.join(modules) + '.\n'
    content += text[offsets[-1]:]
    # Keep the public input name used by the aggregate and allocator root.
    content = content.replace('Definition clashes :=',
        f'Definition input := {modules[0]}.input.\nDefinition clashes :=', 1)
    write_if_changed(path, content)


def split_loop(i, root, chunks, size):
    prefix = f'Word{i:04}'
    previous = prefix + '_03aHeuristics'
    initial = previous + '.selectionInitialized'
    for n in range(chunks):
        module = prefix + f'_Loop{n:04}'
        before = initial if n == 0 else previous + '.loopState'
        content = HEADER + f'From InitE.Compilation Require Import Allocation IRCChunks {prefix}_00Input.\n'
        content += f'From InitE.Compilation Require {previous}.\n'
        content += checkpoint('loopState', f'advance {before} (IRCChunks.run {size} (snd heuristics) regs)')
        content += f'Lemma resume_eq : advance {initial} (reg_alloc.rpt_do_step (snd heuristics) regs) = advance loopState (reg_alloc.rpt_do_step (snd heuristics) regs).\nProof.\n'
        if n:
            content += f' rewrite {previous}.resume_eq.\n'
        content += f' rewrite (IRCChunks.checkpoint_resume {size} (snd heuristics) regs {before}), loopState_eq. reflexivity.\nQed.\n'
        # The initial checkpoint is needed in the theorem statement as well.
        content = content.replace(f'Require {previous}.', f'Require {prefix}_03aHeuristics {previous}.' if n else f'Require {previous}.')
        write_if_changed(root / (module + '.v'), content)
        previous = module
    path = root / (prefix + '_03bLoop.v')
    content = HEADER + f'From InitE.Compilation Require Import Allocation {prefix}_00Input {prefix}_03aHeuristics.\n'
    content += f'From InitE.Compilation Require SparseIRC {previous}.\n'
    content += checkpoint('selectionLoop', f'advance {previous}.loopState (reg_alloc.rpt_do_step (snd heuristics) regs)', f'advance {previous}.loopState (SparseIRC.repeat_fast (snd heuristics) regs)', 'SparseIRC.advance_repeat_fast_exact').replace('Lemma selectionLoop_eq :', 'Lemma selectionLoop_result_eq :')
    content += f'Lemma selectionLoop_eq : advance selectionInitialized (fun count => reg_alloc.rpt_do_step (snd heuristics) regs count) = selectionLoop.\nProof. change (advance selectionInitialized (reg_alloc.rpt_do_step (snd heuristics) regs) = selectionLoop). rewrite {previous}.resume_eq. exact selectionLoop_result_eq. Qed.\n'
    write_if_changed(path, content)


def write_if_changed(path, content):
    content = "\n".join(line.rstrip() for line in content.splitlines()).rstrip() + "\n"
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('count', type=int, help='Eval vm_compute in List.length Frontend.words')
    parser.add_argument('--split-allocation', type=int, nargs='*', default=[0, 57, 87],
                        help='functions needing allocator state checkpoints (default: 0, 57, 87)')
    args = parser.parse_args()
    if args.count <= 0:
        parser.error('count must be positive')
    with TemporaryDirectory(prefix='rocq-checkpoints-') as temporary:
        dest = Path(temporary)
        for i in range(args.count):
            if i not in args.split_allocation:
                write_if_changed(dest / f'Word{i:04}.v', function(i))
        write_if_changed(dest / 'WordPipeline.v', aggregate(args.count))
        for i in args.split_allocation:
            if not 0 <= i < args.count:
                parser.error('split index outside function count')
            split_allocation(i, dest)
        for i in range(args.count):
            split_word_passes(i, dest)
        if 87 in args.split_allocation:
            split_loop(87, dest, chunks=64, size=100)
        if 0 in args.split_allocation:
            split_loop(0, dest, chunks=2, size=2)
        for path in sorted(dest.glob('*.v')):
            write_if_changed(ROOT / 'theories/Compilation' / path.name, path.read_text())


if __name__ == '__main__':
    main()
